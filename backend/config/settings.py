BASE_DIR = Path(__file__).resolve().parent.parent


def _load_env():
    f = BASE_DIR / ".env"
    if f.exists():
        for line in f.read_text().splitlines():
            if "=" in line and not line.startswith("#"):
                k, v = line.split("=", 1)
                os.environ.setdefault(k.strip(), v.strip())


